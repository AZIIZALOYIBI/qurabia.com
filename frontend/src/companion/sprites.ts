export const TICK_MS = 500;

/**
 * رسم إطار واحد من الرفيق.
 */
export function renderSprite(bones: CompanionBones, frameIndex = 0): string[] {
  const frames = SPRITE_FRAMES[bones.species] || SPRITE_FRAMES.qubit;
  const idx = Math.abs(frameIndex) % frames.length;
  const frame = frames[idx];

  const haloLine = bones.halo !== 'none' ? HALO_LINES[bones.halo] : '';

  const rendered = frame.map((line) => line.replace(/\{E\}/g, bones.eye));

  if (haloLine && rendered[0]?.trim() === '') {
    rendered[0] = haloLine;
  }

  if (bones.shiny) {
    rendered[rendered.length - 1] = rendered[rendered.length - 1].replace(/ /g, '✧');
  }

  return rendered;
}

/**
 * عدد الإطارات لنوع معين.
 */
export function spriteFrameCount(_species: Species): number {
  return 3;
}

/**
 * رسم وجه مختصر.
 */
export function renderFace(bones: CompanionBones): string {
  return `(${bones.eye}${bones.species[0].toUpperCase()}${bones.eye})`;
}
